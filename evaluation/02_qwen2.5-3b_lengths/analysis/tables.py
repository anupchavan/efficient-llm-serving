"""data/summary.csv -> results/tables.md: the numbers quoted from this sweep.

Only the four compared configurations are used (label fp16, awq, spec, awq_spec
in summary.csv). One run per setting, so there is no spread to report.
Capacity = mean requests/s served over the sent rates 16-64, where every
configuration has stopped following the sent rate.
"""
import os
import pandas as pd

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
d = pd.read_csv(os.path.join(ROOT, 'data', 'summary.csv'))
d = d[d.label.notna() & (d.label != '')]
assert len(d) == 4 * 54 and (d.failed == 0).all() and (d.completed == 992).all()
CONFIGS = ['fp16', 'awq', 'spec', 'awq_spec']
NAMES = {'fp16': 'FP16', 'awq': 'AWQ', 'spec': 'Speculative', 'awq_spec': 'AWQ + speculative'}
LENS = sorted(d.prompt_len.unique())
A = d.set_index(['label', 'prompt_len', 'rate'])
out = ['# Tables for the 864-run sweep (generated by analysis/tables.py)\n',
       'Qwen2.5-3B-Instruct, prompts with a shared first half (at most 512 tokens, 32 distinct prefixes), '
       'prefix caching on (vLLM default), 992 requests per run, one run per setting.\n']


def table(head, rows):
    out.append('| ' + ' | '.join(head) + ' |')
    out.append('|' + '---|' * len(head))
    out.extend('| ' + ' | '.join(r) + ' |' for r in rows)
    out.append('')


out.append('## Median TPOT (ms) at 2 requests/s, with speed-up over FP16\n')
table(['Prompt tokens'] + [NAMES[c] for c in CONFIGS],
      [[str(n)] + [f"{A.loc[(c, n, 2), 'median_tpot_ms']:.1f}" +
                   ('' if c == 'fp16' else f" ({A.loc[('fp16', n, 2), 'median_tpot_ms'] / A.loc[(c, n, 2), 'median_tpot_ms']:.2f}×)")
                   for c in CONFIGS] for n in LENS])
out.append('## Median TTFT (ms) at 2 requests/s\n')
table(['Prompt tokens'] + [NAMES[c] for c in CONFIGS],
      [[str(n)] + [f"{A.loc[(c, n, 2), 'median_ttft_ms']:.0f}" for c in CONFIGS] for n in LENS])

cap = d[d.rate >= 16].groupby(['label', 'prompt_len']).request_throughput.mean()
ptok = d[d.rate >= 16].assign(p=lambda t: t.total_input_tokens / t.duration).groupby(['label', 'prompt_len']).p.mean()
out.append('## Capacity: requests/s served, mean over sent rates 16-64, relative to FP16 in brackets\n')
table(['Prompt tokens'] + [NAMES[c] for c in CONFIGS],
      [[str(n)] + [f'{cap[(c, n)]:.2f}' + ('' if c == 'fp16' else f' ({cap[(c, n)] / cap[("fp16", n)]:.2f}×)')
                   for c in CONFIGS] for n in LENS])
out.append('## Prompt tokens/s at capacity (all prompt tokens, including the cached shared prefix)\n')
table(['Prompt tokens'] + [NAMES[c] for c in CONFIGS],
      [[str(n)] + [f'{ptok[(c, n)]:,.0f}' for c in CONFIGS] for n in LENS])
out.append('## New prompt tokens/s at capacity (prompt tokens minus the shared prefix, assuming every shared prefix is a cache hit)\n')
new = lambda n: (n - min(512, n // 2)) / n
table(['Prompt tokens'] + [NAMES[c] for c in CONFIGS],
      [[str(n)] + [f'{ptok[(c, n)] * new(n):,.0f}' for c in CONFIGS] for n in LENS])
acc = d[d.label.isin(['spec', 'awq_spec'])].groupby('label').spec_decode_acceptance_rate.agg(['min', 'max'])
out.append('## Speculative decoding acceptance rate (%), range over all rates and lengths\n')
table(['Config', 'min', 'max'], [[NAMES[c], f'{acc.loc[c, "min"]:.1f}', f'{acc.loc[c, "max"]:.1f}'] for c in acc.index])
open(os.path.join(ROOT, 'results', 'tables.md'), 'w').write('\n'.join(out))
print('wrote results/tables.md')
